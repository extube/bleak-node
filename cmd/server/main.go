// bleak-node is the REST server for rooms, users and handshakes.
package main

import (
	"context"
	"errors"
	"fmt"
	"log/slog"
	"net/http"
	"os"
	"os/signal"
	"strings"
	"syscall"
	"time"

	_ "github.com/extube/bleak-node/docs" // swagger docs generated by swag
	"github.com/extube/bleak-node/internal/agent"
	"github.com/extube/bleak-node/internal/db"
	"github.com/extube/bleak-node/internal/model"
	"github.com/extube/bleak-node/internal/server"
)

// @title			bleak-node API
// @version		0.1.0
// @description	REST API for bleak-node: rooms, room users and handshakes, backed by SQLite.
// @BasePath		/
// @Contact.name	extube
// @Contact.url	https://github.com/extube
func main() {
	log := slog.New(slog.NewTextHandler(os.Stderr, nil))

	dbPath := envOr("BLEAK_NODE_DB", "bleak-node.db")
	addr := envOr("BLEAK_NODE_ADDR", "0.0.0.0:8080")

	ctx, stop := signal.NotifyContext(context.Background(), syscall.SIGINT, syscall.SIGTERM)
	defer stop()

	// Short-lived context just for opening/migrating the database.
	dbCtx, dbCancel := context.WithTimeout(ctx, 15*time.Second)
	defer dbCancel()

	database, err := db.Open(dbCtx, dbPath)
	if err != nil {
		log.Error("open database", "path", dbPath, "err", err)
		os.Exit(1)
	}
	defer database.Close()

	srv := &http.Server{
		Addr:              addr,
		Handler:           server.New(database).Handler(),
		ReadHeaderTimeout: 5 * time.Second,
	}

	// Agent interaction worker over the SQLite event queue.
	if cfg := agentConfig(); cfg != nil {
		worker := agent.New(database, *cfg, log)
		go worker.Run(ctx)
		log.Info("agent worker started",
			"llm", cfg.LLMBaseURL, "model", cfg.LLMModel, "max_user_messages", cfg.MaxUserMessages)
	}

	go func() {
		<-ctx.Done()
		log.Info("shutting down")
		shutdownCtx, cancel := context.WithTimeout(context.Background(), 10*time.Second)
		defer cancel()
		_ = srv.Shutdown(shutdownCtx)
	}()

	log.Info("listening", "addr", addr, "db", dbPath)
	if err := srv.ListenAndServe(); err != nil && !errors.Is(err, http.ErrServerClosed) {
		log.Error("server failed", "err", err)
		os.Exit(1)
	}
}

func envOr(key, fallback string) string {
	if v := os.Getenv(key); v != "" {
		return v
	}
	return fallback
}

// agentConfig builds the agent worker configuration from the environment;
// nil when the agent worker is disabled via BLEAK_NODE_AGENT=0.
func agentConfig() *agent.Config {
	if os.Getenv("BLEAK_NODE_AGENT") == "0" {
		return nil
	}
	return &agent.Config{
		LLMBaseURL: envOr("BLEAK_NODE_LLM_URL", "http://localhost:8000/v1"),
		LLMModel:   envOr("BLEAK_NODE_LLM_MODEL", "gemma-4-e2b-agent"),
		APIKey:     envOr("BLEAK_NODE_LLM_API_KEY", envOr("OPENROUTER_API_KEY", "")),
		// Thinking channel is disabled unless BLEAK_NODE_LLM_THINKING=1:
		// the local qwen model otherwise buries the answer in reasoning_content.
		DisableThinking: !envBool("BLEAK_NODE_LLM_THINKING", false),
		MaxUserMessages: clampEnvInt("BLEAK_NODE_CHAT_LIMIT",
			model.DefaultUserMessageLimit, model.MinUserMessageLimit, model.MaxUserMessageLimit),
	}
}

// clampEnvInt reads an int env var and falls back when unset or malformed;
// the result is clamped into [lo, hi].
func clampEnvInt(key string, fallback, lo, hi int) int {
	v := envInt(key, fallback)
	if v < lo {
		return lo
	}
	if v > hi {
		return hi
	}
	return v
}

// envBool reports whether the env var is truthy; unset keeps the fallback.
func envBool(key string, fallback bool) bool {
	v := os.Getenv(key)
	switch strings.ToLower(v) {
	case "1", "true", "yes", "on":
		return true
	case "0", "false", "no", "off":
		return false
	}
	return fallback
}

func envInt(key string, fallback int) int {
	if v := os.Getenv(key); v != "" {
		var n int
		if _, err := fmt.Sscanf(v, "%d", &n); err == nil {
			return n
		}
	}
	return fallback
}
