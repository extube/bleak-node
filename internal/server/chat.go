package server

import (
	"errors"
	"fmt"
	"net/http"
	"unicode/utf8"

	"github.com/extube/bleak-node/internal/db"
	"github.com/extube/bleak-node/internal/model"
)

// ChatResponse is a chat with its participants.
type ChatResponse struct {
	model.Chat
	Participants []model.Participant `json:"participants"`
}

// SendMessageRequest is the body for POST /api/message.
type SendMessageRequest struct {
	From    string `json:"from"`
	To      string `json:"to"`
	Content string `json:"content"`
}

// SendMessage posts a message inside the chat between two users.
//
//	@Summary		send message
//	@Description	Posts a message from one user to another inside their chat. The chat must exist: it is created automatically once handshakes exist in both directions (A -> B and B -> A) between the two users. Content is limited to 255 symbols, the tx id and created_at are generated by the server.
//	@Tags			messages
//	@Accept			json
//	@Produce		json
//	@Param			request	body	SendMessageRequest	true	"Message to send"
//	@Success		201	{object}	model.Message
//	@Failure		400	{object}	string
//	@Failure		404	{object}	string
//	@Failure		409	{object}	string
//	@Router			/api/message [post]
func (s *Server) SendMessage(w http.ResponseWriter, r *http.Request) {
	var req SendMessageRequest
	if err := decodeJSON(r, &req); err != nil {
		respond(w, http.StatusBadRequest, message(err))
		return
	}

	if req.From == "" {
		respond(w, http.StatusBadRequest, "from is required")
		return
	}
	if req.To == "" {
		respond(w, http.StatusBadRequest, "to is required")
		return
	}
	if req.From == req.To {
		respond(w, http.StatusBadRequest, "from and to must differ")
		return
	}
	if n := utf8.RuneCountInString(req.Content); n > model.MaxMessageContentLen {
		respond(w, http.StatusBadRequest, "content must be at most 255 symbols")
		return
	}

	m := model.Message{From: req.From, To: req.To, Content: req.Content}
	if err := s.db.CreateMessage(r.Context(), &m); err != nil {
		s.mapError(w, err)
		return
	}
	writeJSON(w, http.StatusCreated, m)
}

// ListUserChats returns all chats of a user.
//
//	@Summary		list chats of a user
//	@Description	Returns every chat the user participates in, newest first.
//	@Tags			chats
//	@Produce		json
//	@Param			address	path	string	true	"User address"
//	@Success		200	{array}	ChatResponse
//	@Router			/api/user/{address}/chat [get]
func (s *Server) ListUserChats(w http.ResponseWriter, r *http.Request) {
	chats, err := s.db.ListUserChats(r.Context(), r.PathValue("address"))
	if err != nil {
		s.mapError(w, err)
		return
	}

	out := []ChatResponse{}
	for _, c := range chats {
		parts, err := s.db.ChatParticipants(r.Context(), c.Address)
		if err != nil {
			s.mapError(w, err)
			return
		}
		out = append(out, ChatResponse{Chat: c, Participants: parts})
	}
	writeJSON(w, http.StatusOK, out)
}

// GetChat returns a chat with its participants.
//
//	@Summary		get chat
//	@Description	Returns one chat together with its participants.
//	@Tags			chats
//	@Produce		json
//	@Param			address	path	string	true	"Chat address"
//	@Success		200	{object}	ChatResponse
//	@Failure		404	{object}	string
//	@Router			/api/chat/{address} [get]
func (s *Server) GetChat(w http.ResponseWriter, r *http.Request) {
	chat, parts, err := s.db.GetChat(r.Context(), r.PathValue("address"))
	if err != nil {
		s.mapError(w, err)
		return
	}
	writeJSON(w, http.StatusOK, ChatResponse{Chat: chat, Participants: parts})
}

// ListChatMessages returns all messages of a chat.
//
//	@Summary		list messages of a chat
//	@Description	Returns every message in the chat, oldest first.
//	@Tags			messages
//	@Produce		json
//	@Param			address	path	string	true	"Chat address"
//	@Success		200	{array}	model.Message
//	@Failure		404	{object}	string
//	@Router			/api/chat/{address}/message [get]
func (s *Server) ListChatMessages(w http.ResponseWriter, r *http.Request) {
	exists, err := s.db.ChatExists(r.Context(), r.PathValue("address"))
	if err != nil {
		s.mapError(w, err)
		return
	}
	if !exists {
		s.mapError(w, errors.Join(db.ErrNotFound, fmt.Errorf("chat %q not found", r.PathValue("address"))))
		return
	}
	msgs, err := s.db.ListChatMessages(r.Context(), r.PathValue("address"))
	if err != nil {
		s.mapError(w, err)
		return
	}
	writeJSON(w, http.StatusOK, msgs)
}
