// ChatResponse is a chat with its participants.
type ChatResponse struct {
	model.Chat
	Participants []model.Participant `json:"participants"`
}

// SendMessageRequest is the body for POST /api/message.
type SendMessageRequest struct {
	From    string `json:"from"`
	To      string `json:"to"`
	Content string `json:"content"`
}

// SendMessage posts a message inside the chat between two users. Requires
// the from persona's token (the agent runtime keeps its internal
// token-free path).
//
//	@Summary		send message
//	@Description	Posts a message from one user to another inside their chat. Requires the from persona's Bearer token. The chat must exist: it is created automatically once handshakes exist in both directions (A -> B and B -> A) between the two users. Content is limited to 255 symbols, the tx id and created_at are generated by the server.
//	@Tags			messages
//	@Security		UserToken
//	@Accept			json
//	@Produce		json
//	@Param			request	body	SendMessageRequest	true	"Message to send"
//	@Success		201	{object}	model.Message
//	@Failure		400	{object}	string
//	@Failure		401	{object}	string
//	@Failure		403	{object}	string
//	@Failure		404	{object}	string
//	@Failure		409	{object}	string
//	@Router			/api/message [post]
func (s *Server) SendMessage(w http.ResponseWriter, r *http.Request) {
	var req SendMessageRequest
	if err := decodeJSON(r, &req); err != nil {
		respond(w, http.StatusBadRequest, message(err))
		return
	}

	if req.From == "" {
		respond(w, http.StatusBadRequest, "from is required")
		return
	}
	if req.To == "" {
		respond(w, http.StatusBadRequest, "to is required")
		return
	}
	if req.From == req.To {
		respond(w, http.StatusBadRequest, "from and to must differ")
		return
	}
	if n := utf8.RuneCountInString(req.Content); n > model.MaxMessageContentLen {
		respond(w, http.StatusBadRequest, "content must be at most 255 symbols")
		return
	}
	if !s.authUserTokenByAddress(w, r, req.From) {
		return
	}

	m := model.Message{From: req.From, To: req.To, Content: req.Content}
	if err := s.db.CreateMessage(r.Context(), &m); err != nil {
		s.mapError(w, err)
		return
	}
	writeJSON(w, http.StatusCreated, m)
}

// ListUserChats returns all chats of a user. Gated read: requires that
// persona's token.
//
//	@Summary		list chats of a user
//	@Description	Returns every chat the user participates in, newest first. Requires that persona's Bearer token.
//	@Tags			chats
//	@Security		UserToken
//	@Produce		json
//	@Param			address	path	string	true	"User address"
//	@Success		200	{array}	ChatResponse
//	@Failure		401	{object}	string
//	@Failure		403	{object}	string
//	@Router			/api/user/{address}/chat [get]
func (s *Server) ListUserChats(w http.ResponseWriter, r *http.Request) {
	if !s.authUserTokenByAddress(w, r, r.PathValue("address")) {
		return
	}
	chats, err := s.db.ListUserChats(r.Context(), r.PathValue("address"))
	if err != nil {
		s.mapError(w, err)
		return
	}

	out := []ChatResponse{}
	for _, c := range chats {
		parts, err := s.db.ChatParticipants(r.Context(), c.Address)
		if err != nil {
			s.mapError(w, err)
			return
		}
		out = append(out, ChatResponse{Chat: c, Participants: parts})
	}
	writeJSON(w, http.StatusOK, out)
}

// GetChat returns a chat with its participants. Gated read: a participant
// persona's token or the room token.
//
//	@Summary		get chat
//	@Description	Returns one chat together with its participants. Requires a participant persona's Bearer token or the room token.
//	@Tags			chats
//	@Security		UserToken
//	@Produce		json
//	@Param			address	path	string	true	"Chat address"
//	@Success		200	{object}	ChatResponse
//	@Failure		401	{object}	string
//	@Failure		403	{object}	string
//	@Failure		404	{object}	string
//	@Router			/api/chat/{address} [get]
func (s *Server) GetChat(w http.ResponseWriter, r *http.Request) {
	if !s.authParticipantOrRoomToken(w, r, r.PathValue("address")) {
		return
	}
	chat, parts, err := s.db.GetChat(r.Context(), r.PathValue("address"))
	if err != nil {
		s.mapError(w, err)
		return
	}
	writeJSON(w, http.StatusOK, ChatResponse{Chat: chat, Participants: parts})
}

// ClearChatResponse reports the history clearing result.
type ClearChatResponse struct {
	Chat    string `json:"chat"`
	Cleared int64  `json:"cleared"`
}

// ClearChatMessages removes the message history of a chat. The chat and its
// participants stay; chats themselves are never deleted. A repeated
// handshake for the pair restarts the interaction on the empty chat.
// Requires a participant persona's token or the room token (full room
// control).
//
//	@Summary		clear chat history
//	@Description	Deletes every message of the chat. The chat and its participants remain. Requires a participant persona's Bearer token or the room token.
//	@Tags			chats
//	@Security		UserToken
//	@Produce		json
//	@Param			address	path	string	true	"Chat address"
//	@Success		200	{object}	ClearChatResponse
//	@Failure		401	{object}	string
//	@Failure		403	{object}	string
//	@Failure		404	{object}	string
//	@Router			/api/chat/{address}/message [delete]
func (s *Server) ClearChatMessages(w http.ResponseWriter, r *http.Request) {
	if !s.authParticipantOrRoomToken(w, r, r.PathValue("address")) {
		return
	}
	address := r.PathValue("address")
	cleared, err := s.db.ClearChatMessages(r.Context(), address)
	if err != nil {
		s.mapError(w, err)
		return
	}
	writeJSON(w, http.StatusOK, ClearChatResponse{Chat: address, Cleared: cleared})
}

// KickoffResponse reports the chat restart result.
type KickoffResponse struct {
	Chat    string `json:"chat"`
	Cleared int64  `json:"cleared"`
	Speaker string `json:"speaker"`
}

// ChatKickoff clears the message history and restarts the agent
// interaction. The speaker of the first turn is the user who sent the
// earliest of the pair's handshakes (as on chat creation).
//
//	@Summary		kick off chat
//	@Description	Clears the message history of the chat and returns the interaction to the queue. The speaker of the first turn is the user who sent the pair's earliest handshake; the agents then continue automatically until the chat limit. Requires a participant persona's Bearer token or the room token.
//	@Tags			chats
//	@Security		UserToken
//	@Produce		json
//	@Param			address	path	string	true	"Chat address"
//	@Success		201	{object}	KickoffResponse
//	@Failure		401	{object}	string
//	@Failure		403	{object}	string
//	@Failure		404	{object}	string
//	@Router			/api/chat/{address}/kickoff [post]
func (s *Server) ChatKickoff(w http.ResponseWriter, r *http.Request) {
	if !s.authParticipantOrRoomToken(w, r, r.PathValue("address")) {
		return
	}
	address := r.PathValue("address")
	res, err := s.db.ChatKickoff(r.Context(), address)
	if err != nil {
		s.mapError(w, err)
		return
	}
	writeJSON(w, http.StatusCreated, KickoffResponse(res))
}

