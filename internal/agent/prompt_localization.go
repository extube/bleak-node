func localizedTheme(theme Theme, language string) Theme {
	if !isRussian(language) {
		return theme
	}
	text, ok := russianThemes[theme.Key]
	if !ok {
		text = russianThemeText{
			name:        "Тема для разговора",
			description: "Обсуждение повседневной жизни и личных взглядов.",
			hello:       "Коротко выскажи своё мнение по теме и спроси мнение собеседника.",
			context:     "Обсуждайте тему дружелюбно и через повседневный опыт. Не выдумывай личные факты.",
		}
	}
	theme.Name = text.name
	theme.Description = text.description
	theme.Scenario.Hello = text.hello
	theme.Scenario.Context = text.context
	theme.Scenario.Goodbye = "Чат подходит к концу. Коротко и тепло попрощайся, как в обычной переписке."
	return theme
}
